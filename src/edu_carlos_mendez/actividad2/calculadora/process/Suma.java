package edu_carlos_mendez.actividad2.calculadora.process;

public class Suma {
    /**
     * Este método recibe 2 operandos enteros y devuelve una suma
     * @param op1 primer operando
     * @param op2 segundo operando
     * @return resultado de la suma
     */
    public static   int realizarOperacion(int op1,int op2){
        return  op1+op2;
    }
}
